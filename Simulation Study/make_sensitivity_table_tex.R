# make_sensitivity_table_tex.R
# LaTeX table of the Supplement's sensitivity analysis (Tab:Sensitivity) from the summary written by
# run_sensitivity.R (Results/Sensitivity/Tables/sensitivity_summary.csv). No sampling.
# Writes Results/Paper_Tables/sensitivity_table.tex.
# Cells, per scenario and n (medians over the five datasets, as in sensitivity_summary.csv):
#   Est. Error       = rel_change_median_pct: median relative change (%) of the relative L2 error vs baseline;
#   Post. Mean Change = delta_mean_median_pct: median of ||mean - mean_base|| / ||rho_0|| (%), see SENSITIVITY_SPEC.md;
#   last row          = median over the settings of mc_envelope_median_pct, the Monte Carlo yardstick
#                       sqrt(mcse^2 + mcse_base^2) / ||rho_0|| (%).
# Added 19 October 2026; not part of the checksummed runner sources.
#
# Run from 'Data Analysis/Simulation Study':  Rscript make_sensitivity_table_tex.R

s <- read.csv(file.path("Results", "Sensitivity", "Tables", "sensitivity_summary.csv"), stringsAsFactors = FALSE)
rows <- list(
  c("S1_coarse", "$w$: $V=100$ / $15\\times15$"), c("S1_fine", "$w$: $V=400$ / $35\\times35$"),
  c("S2_coarse", "Binning: $500$ / $100^2$"),    c("S2_fine", "Binning: $8000$ / $400^2$"), NULL,
  c("S3_q25", "Quadrature: $q=25$"),            c("S3_q100", "Quadrature: $q=100$"), NULL,
  c("S4a_cInf", "$c_{\\rho^*}=\\infty$"),       c("S4b_b0p01", "$b_{\\rho^*}=0.01$"), c("S4b_b2", "$b_{\\rho^*}=2$"),
  c("S5_l0p05", "$\\lambda=0.05$"),             c("S5_l0p25", "$\\lambda=0.25$"),
  c("S6_a1b1p5", "$b_\\ell=1.5$"),              c("S6_a1b4", "$b_\\ell=4$"))
cols <- list(c("1d_skn", 50), c("1d_skn", 1000), c("2d_hole", 50), c("2d_hole", 1000))
signed <- function(x) { x <- round(x, 1); if (x == 0) "$0.0$" else sprintf("$%+.1f$", x) }
plain  <- function(x) sprintf("$%.1f$", round(x, 1) + 0)
get <- function(set, sc, n) {
  a <- s[s$setting == set & s$scenario == sc & s$n == as.integer(n), ]
  if (nrow(a) != 1) stop("Missing or duplicated row: ", set, " ", sc, " n=", n)
  if (a$datasets != 5) warning(set, " ", sc, " n=", n, ": ", a$datasets, " datasets")
  a
}
out <- c("\\makebox[\\textwidth][c]{%", "\\begin{tabular}{l|cc|cc|cc|cc}",
  "\t& \\multicolumn{4}{c|}{\\textbf{Univariate setting}} & \\multicolumn{4}{c}{\\textbf{Bivariate setting}} \\\\",
  "\t& \\multicolumn{2}{c|}{$n=50$} & \\multicolumn{2}{c|}{$n=1000$} & \\multicolumn{2}{c|}{$n=50$} & \\multicolumn{2}{c}{$n=1000$} \\\\",
  "\t& Est. & Post. Mean & Est. & Post. Mean & Est. & Post. Mean & Est. & Post. Mean \\\\",
  "\t\\textbf{Setting} & Error & Change & Error & Change & Error & Change & Error & Change \\\\",
  "\t\\hline")
for (r in rows) {
  if (is.null(r)) { out <- c(out, "\t\\hline"); next }
  cells <- unlist(lapply(cols, function(cn) { a <- get(r[1], cn[1], cn[2])
    c(signed(a$rel_change_median_pct), plain(a$delta_mean_median_pct)) }))
  out <- c(out, sprintf("\t%s & %s \\\\", r[2], paste(cells, collapse = " & ")))
}
mc <- unlist(lapply(cols, function(cn) {
  a <- s[s$scenario == cn[1] & s$n == as.integer(cn[2]), ]
  c("--", plain(median(a$mc_envelope_median_pct))) }))
out <- c(out, "\t\\hline", sprintf("\tMonte Carlo error & %s \\\\", paste(mc, collapse = " & ")),
         "\t\\hline", "\\end{tabular}%", "}",
         sprintf("%% Generated by make_sensitivity_table_tex.R from Results/Sensitivity/Tables/sensitivity_summary.csv (%s datasets per cell).",
                 paste(sort(unique(s$datasets)), collapse = "/")),
         "% Post. Mean Change is normalised by the L2-norm of the true intensity (SENSITIVITY_SPEC.md), not of the baseline posterior mean.")
dir.create(file.path("Results", "Paper_Tables"), recursive = TRUE, showWarnings = FALSE)
f <- file.path("Results", "Paper_Tables", "sensitivity_table.tex")
writeLines(out, f)
cat(out, sep = "\n"); cat("\nWritten:", f, "\n")
