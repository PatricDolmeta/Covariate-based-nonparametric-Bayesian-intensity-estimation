# make_supplement_tables_tex.R
# LaTeX tables of the Supplement's additional experiments (Tab:1DTab2, Tab:2DResults3,
# Tab:2DResultsCoord), in the format of the main paper's Tab:Errors. No sampling.
# Reads <out>/Tables/error_table.csv, truth_norms.csv and overparam_vs_main_1d.csv
# (written by run_additional_simulations.R) and writes <out>/Paper_Tables/supplement_tables.tex.
# Cells: mean relative L2 error over the datasets (between-dataset SD); bold = smallest mean in
# each column within each ground truth. In the over-parametrised block, the extra row in italics is
# the main study's univariate fit of the same observations (paired by data_id); it is not bolded.
# Added 19 October 2026; not part of the checksummed runner sources.
#
# Run from 'Data Analysis/Additional Simulations':  Rscript make_supplement_tables_tex.R [--out=DIR]

args <- commandArgs(TRUE)
OUT <- if (any(startsWith(args, "--out="))) sub("^--out=", "", args[startsWith(args, "--out=")][1]) else
  file.path("Results", "Additional_Simulations")
e <- read.csv(file.path(OUT, "Tables", "error_table.csv"), stringsAsFactors = FALSE)
norms <- read.csv(file.path(OUT, "Tables", "truth_norms.csv"), stringsAsFactors = FALSE)
ovp <- read.csv(file.path(OUT, "Tables", "overparam_vs_main_1d.csv"), stringsAsFactors = FALSE)
ns <- c(50L, 250L, 500L, 1000L)
methods <- list(c("GP", "Posterior mean"), NULL, c("Kernel_CV", "Kernel, CV"), c("Kernel_oracle", "Kernel, oracle"), NULL,
                c("Log_poly1", "Log-polynomial, $k=1$"), c("Log_poly2", "Log-polynomial, $k=2$"),
                c("Log_poly3", "Log-polynomial, $k=3$"), c("Log_poly4", "Log-polynomial, $k=4$"))
sep <- "\t\\noalign{{\\color{gray!60}\\hrule height 0.3pt}}"
nrm <- function(s) sprintf("%.2f", norms$L2_norm[norms$scenario == s])

block <- function(s, title) {
  x <- e[e$scenario == s, ]
  best <- vapply(ns, function(n) min(x$mean_relative_L2[x$n == n]), 0)
  out <- c("\t\\noalign{\\vskip 3pt}", sprintf("\t\\multicolumn{5}{c}{\\textbf{%s}}\\\\", title), "\t\\noalign{\\vskip 3pt}")
  for (r in methods) {
    if (is.null(r)) { out <- c(out, sep); next }
    cells <- vapply(seq_along(ns), function(j) {
      y <- x[x$n == ns[j] & x$method == r[1], ]
      if (nrow(y) != 1) stop("Missing cell: ", s, " n=", ns[j], " ", r[1])
      m <- sprintf("%.3f", y$mean_relative_L2)
      if (abs(y$mean_relative_L2 - best[j]) < 1e-12) m <- sprintf("\\textbf{%s}", m)
      sprintf("%s (%.3f)", m, y$sd_relative_L2)
    }, "")
    out <- c(out, sprintf("\t%s & %s \\\\", r[2], paste(cells, collapse = " & ")))
    if (s == "2d_overparam" && r[1] == "GP") {          # reference: univariate fit of the same data
      ref <- vapply(ns, function(n) { y <- ovp[ovp$n == n & ovp$method == "GP", ]; stopifnot(nrow(y) == 1)
        sprintf("\\textit{%.3f}", y$mean_main_1d) }, "")
      out <- c(out, sprintf("\t\\textit{Posterior mean, univariate model} & %s \\\\", paste(ref, collapse = " & ")))
    }
  }
  c(out, "\t\\hline")
}
table_env <- function(blocks, caption, label) {
  k <- unique(e$datasets[e$scenario %in% names(blocks)])
  if (length(k) != 1) warning(label, ": cells have different numbers of datasets: ", paste(k, collapse = ", "))
  c("\\begin{table}[H]%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%", "\\centering", "\\small", "\\color{blue}",
    "\\begin{tabular}{l|cccc}", "\t& $n=50$ & $n=250$ & $n=500$ & $n=1000$ \\\\", "\t\\hline",
    unlist(Map(block, names(blocks), blocks)), "\t\\end{tabular}",
    sprintf("\\caption{%s}", sprintf(caption, paste(k, collapse = "/"))), sprintf("\\label{%s}", label),
    "\\end{table}%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%", "")
}
cap <- "Mean relative $L^2$-errors (and between-dataset standard deviations) over %%s independent datasets for each ground truth and sample size. %s"
out <- c(sprintf("%% Generated by make_supplement_tables_tex.R from %s/Tables (%s).", OUT, format(Sys.Date())), "",
  table_env(c("1d_negexp" = "Ground truth \\eqref{Eq:1DTruth2}", "1d_minmax" = "Ground truth \\eqref{Eq:1DTruth3}"),
    sprintf(cap, sprintf("For $\\rho_0$ as in \\eqref{Eq:1DTruth2}, $\\|\\rho_0\\|_{L^2} = %s$; for $\\rho_0$ as in \\eqref{Eq:1DTruth3}, $\\|\\rho_0\\|_{L^2} = %s$.",
                         nrm("1d_negexp"), nrm("1d_minmax"))), "Tab:1DTab2"),
  table_env(c("2d_slope" = "Ground truth \\eqref{Eq:2DTruth3}", "2d_twobump" = "Ground truth \\eqref{Eq:2DTruth2}"),
    sprintf(cap, sprintf("For $\\rho_0$ as in \\eqref{Eq:2DTruth3}, $\\|\\rho_0\\|_{L^2} = %s$; for $\\rho_0$ as in \\eqref{Eq:2DTruth2}, $\\|\\rho_0\\|_{L^2} = %s$.",
                         nrm("2d_slope"), nrm("2d_twobump"))), "Tab:2DResults3"),
  table_env(c("2d_detcov" = "Ground truth \\eqref{Eq:2DTruthCoord}", "2d_overparam" = "Ground truth \\eqref{Eq:1DTruth}, over-parametrized"),
    sprintf(cap, sprintf(paste0("For $\\rho_0$ as in \\eqref{Eq:2DTruthCoord}, $\\|\\rho_0\\|_{L^2} = %s$; for $\\rho_0$ as in \\eqref{Eq:2_overparam}, $\\|\\rho_0\\|_{L^2} = %s$. ",
                         "In italics: the posterior mean of the univariate model of Section~\\ref{Subsec:1DExp} on the same datasets."),
                         nrm("2d_detcov"), nrm("2d_overparam"))), "Tab:2DResultsCoord"))
dir.create(file.path(OUT, "Paper_Tables"), recursive = TRUE, showWarnings = FALSE)
f <- file.path(OUT, "Paper_Tables", "supplement_tables.tex")
writeLines(out, f)
cat(out, sep = "\n"); cat("\nWritten:", f, "\n")
